export function translator(locale: string) {
  const language = locale.toLowerCase().split('-')[0]
  const index = language === 'nl' ? 1 : language === 'fr' ? 2 : 0
  return (key: string, fallback = key) => Object.hasOwn(labels, key) ? labels[key as keyof typeof labels][index] : fallback
}
